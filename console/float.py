# ==========================================
# NÚMEROS DECIMALES - float
# ==========================================
# Los float representan números que tienen
# una parte decimal.

precio = 19.99
altura = 1.75
temperatura = 25.5

print(precio)
print(altura)
print(temperatura)


# ------------------------------------------
# Saber el tipo de dato
# ------------------------------------------

print(type(precio))

# Resultado:
# <class 'float'>


# ------------------------------------------
# Operaciones
# ------------------------------------------

a = 10.5
b = 2.5

print(a + b)
print(a - b)
print(a * b)
print(a / b)


