# ------------------------------------------
# Operaciones matemáticas
# ------------------------------------------

a = 10
b = 3

print(a + b)  # Suma
print(a - b)  # Resta
print(a * b)  # Multiplicación
print(a / b)  # División
print(a // b) # División entera
print(a % b)  # Módulo
print(a ** b) # Potencia


